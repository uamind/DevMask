const TABLE: Record<ServerLocale, ServerMessages> = { zh, en, tr }

export function pickServerMessages(locale: string | undefined): ServerMessages {
  return TABLE[(locale as ServerLocale) ?? 'zh'] ?? TABLE.zh
}

function withArgs(template: string, args: Record<string, string | number>): string {
  let result = template
  for (const [key, value] of Object.entries(args)) {
    result = result.replace(new RegExp(`\\{${key}\\}`, 'g'), String(value))
  }
  return result
}

/**
 * 把 `ApiError` 转成一句可展示的话（含 details / requestId / Retry-After）。
 *
 * 契约 §10.5 的状态映射：401 登录、403 作用域、412 版本冲突、409 重复包名、
 * 422 字段级错误、429 限流、5xx 带 requestId。
 */
export function describeApiError(error: unknown, messages: ServerMessages): string {
  if (isUnsupportedError(error)) {
    return error.message || messages.api.unsupported
  }

  if (!isApiError(error)) {
    return error instanceof Error ? error.message : String(error)
  }

  const apiError: ApiError = error
  const requestIdSuffix = apiError.requestId
    ? `（${messages.api.requestId}: ${apiError.requestId}）`
    : ''

  switch (apiError.code) {
    case 'unauthorized':
      return `${messages.api.unauthorized}${requestIdSuffix}`
    case 'forbidden_scope': {
      const { required } = readScopeDetails(apiError)
      const requiredText = required && required.length > 0 ? ` (${required.join(', ')})` : ''
      return `${messages.api.forbidden}${requiredText}${requestIdSuffix}`
    }
    case 'config_revision_mismatch':
      return `${messages.api.revisionMismatch}${requestIdSuffix}`
    case 'conflict_duplicate_package': {
      const conflict = readConflictDetails(apiError)
      const parts = [conflict.packageName, conflict.templates.join(' / ')].filter(Boolean)
      return `${messages.api.duplicatePackage}${parts.length ? `: ${parts.join(' — ')}` : ''}${requestIdSuffix}`
    }
    case 'validation_failed': {
      const items = listValidationErrors(apiError)
      const detail = items
        .slice(0, 3)
        .map((item) => `${item.path || '-'}: ${item.message || item.code}`)
        .join('; ')
      return `${messages.api.validation}${detail ? `: ${detail}` : ''}${requestIdSuffix}`
    }
    case 'rate_limited': {
      const seconds = apiError.retryAfterSec
      return seconds
        ? withArgs(messages.api.saveBlocked, { seconds })
        : `${messages.api.rateLimited}${requestIdSuffix}`
    }
    case 'precondition_required':
      return `${messages.api.revisionMismatch}${requestIdSuffix}`
    default:
      // 注意：这里不能用 isAuthError 收窄——ApiError 已经是同一类型，会被收窄成 never
      if (apiError.status === 401) {
        return `${messages.api.unauthorized}${requestIdSuffix}`
      }
      if (apiError.status >= 500) {
        return `${messages.api.serverError}（HTTP ${apiError.status}）${requestIdSuffix}`
      }
      return `${apiError.message}${requestIdSuffix}`
  }
}
